#!/bin/sh
# Railway first-boot and every-boot setup for Relaticle. Runs as root from the
# image's entrypoint before s6 starts nginx, PHP-FPM, the workers and Reverb.
# Any failure exits non-zero, so the deploy fails or Railway restarts it.
set -eu
APP=/var/www/html
STORE=$APP/storage/app
as_www() { /command/s6-setuidgid www-data "$@"; }
artisan() { as_www php "$APP/artisan" "$@" --no-interaction; }

echo "railway-init: preparing the storage volume"
rm -r "$STORE/lost+found" 2>/dev/null || true
mkdir -p "$STORE/public" "$STORE/private" "$STORE/imports"
chown -R www-data:www-data "$STORE"

# Passport (OAuth for the REST API and MCP) needs an RSA key pair; upstream
# leaves it to the deployer. Keep one pair on the volume so tokens survive redeploys.
if [ -z "${PASSPORT_PRIVATE_KEY:-}" ]; then
  K=$STORE/private/passport
  mkdir -p "$K"
  if [ ! -s "$K/oauth-private.key" ] || [ ! -s "$K/oauth-public.key" ]; then
    echo "railway-init: generating Passport keys on the volume"
    openssl genrsa -out "$K/oauth-private.key" 4096 2>/dev/null
    openssl rsa -in "$K/oauth-private.key" -pubout -out "$K/oauth-public.key" 2>/dev/null
  fi
  chown -R www-data:www-data "$K"; chmod 700 "$K"; chmod 600 "$K"/oauth-*.key
  ln -sf "$K/oauth-private.key" "$APP/storage/oauth-private.key"
  ln -sf "$K/oauth-public.key" "$APP/storage/oauth-public.key"
fi

echo "railway-init: waiting for Postgres and Redis"
artisan config:clear >/dev/null
deadline=$(( $(date +%s) + 180 ))
until as_www php /usr/local/share/railway/check-services.php; do
  if [ "$(date +%s)" -ge "$deadline" ]; then echo "railway-init: Postgres or Redis still unreachable after 3 minutes" >&2; exit 1; fi
  sleep 3
done

# --isolated takes a Redis lock, so overlapping deploys never migrate at once.
# A deploy that loses the lock waits until the winner has finished.
echo "railway-init: running database migrations"
deadline=$(( $(date +%s) + 300 ))
until artisan migrate --force --isolated >/tmp/migrate.log 2>&1 \
      && artisan migrate:status --pending 2>/dev/null | grep -q "No pending migrations"; do
  if [ "$(date +%s)" -ge "$deadline" ]; then echo "railway-init: migrations did not finish" >&2; tail -n 40 /tmp/migrate.log >&2; exit 1; fi
  sleep 5
done
tail -n 3 /tmp/migrate.log

artisan storage:link >/dev/null 2>&1 || true
artisan config:cache >/dev/null
artisan route:cache >/dev/null
artisan view:cache >/dev/null
artisan event:cache >/dev/null

# First admin: a verified CRM user plus a system administrator with the same
# login, created once from ADMIN_EMAIL / ADMIN_PASSWORD (generated by the template).
if [ -n "${ADMIN_EMAIL:-}" ] && [ -n "${ADMIN_PASSWORD:-}" ]; then
  as_www php /usr/local/share/railway/ensure-admin.php
else
  echo "railway-init: ADMIN_EMAIL or ADMIN_PASSWORD is empty, no admin created"
fi
echo "railway-init: done"
